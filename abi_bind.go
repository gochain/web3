package web3

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"
)

// GenerateGoBinding generates a gofmt-formatted Go contract wrapper using package web3.
func GenerateGoBinding(pkgName, typeName, abiJSON, binHex string) ([]byte, error) {
	if pkgName == "" {
		pkgName = "main"
	}
	if typeName == "" {
		typeName = exportGoIdent(pkgName)
		if typeName == "Main" {
			typeName = "Contract"
		}
	} else {
		typeName = exportGoIdent(typeName)
	}

	parsed, err := ParseABI(abiJSON)
	if err != nil {
		return nil, fmt.Errorf("invalid ABI JSON: %w", err)
	}

	var methodKeys []string
	for k, m := range parsed.Methods {
		if k == m.Sig() {
			continue
		}
		methodKeys = append(methodKeys, k)
	}
	sort.Strings(methodKeys)

	needsBig := binHex != ""
	for _, k := range methodKeys {
		m := parsed.Methods[k]
		if !m.IsConstant() {
			needsBig = true
		}
		for _, a := range m.Inputs {
			if abiTypeUsesBigInt(a.Type) {
				needsBig = true
			}
		}
		for _, a := range m.Outputs {
			if abiTypeUsesBigInt(a.Type) {
				needsBig = true
			}
		}
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by web3 generate code. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	fmt.Fprintf(&buf, "import (\n")
	fmt.Fprintf(&buf, "\t\"context\"\n")
	if needsBig {
		fmt.Fprintf(&buf, "\t\"math/big\"\n")
	}
	fmt.Fprintf(&buf, "\n\t\"github.com/gochain/web3\"\n")
	fmt.Fprintf(&buf, ")\n\n")

	fmt.Fprintf(&buf, "const %sABI = %q\n\n", typeName, abiJSON)
	if binHex != "" {
		fmt.Fprintf(&buf, "const %sBin = %q\n\n", typeName, binHex)
	}

	fmt.Fprintf(&buf, "type %s struct {\n", typeName)
	fmt.Fprintf(&buf, "\taddress web3.Address\n")
	fmt.Fprintf(&buf, "\tabi     web3.ABI\n")
	fmt.Fprintf(&buf, "\tclient  web3.Client\n")
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "func New%s(address web3.Address, client web3.Client) (*%s, error) {\n", typeName, typeName)
	fmt.Fprintf(&buf, "\tparsed, err := web3.ParseABI(%sABI)\n", typeName)
	fmt.Fprintf(&buf, "\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	fmt.Fprintf(&buf, "\treturn &%s{address: address, abi: parsed, client: client}, nil\n", typeName)
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "func (c *%s) Address() web3.Address { return c.address }\n\n", typeName)

	if binHex != "" {
		fmt.Fprintf(&buf, "func Deploy%s(ctx context.Context, client web3.Client, privateKeyHex string, gasPrice *big.Int, gasLimit uint64, args ...interface{}) (*web3.Transaction, error) {\n", typeName)
		fmt.Fprintf(&buf, "\treturn web3.DeployContract(ctx, client, privateKeyHex, %sBin, %sABI, gasPrice, gasLimit, args...)\n", typeName, typeName)
		fmt.Fprintf(&buf, "}\n\n")
	}

	for _, k := range methodKeys {
		m := parsed.Methods[k]
		fnName := exportGoIdent(m.Name)
		var paramDecls []string
		var callArgs []string
		for i, in := range m.Inputs {
			argName := safeParamName(in.Name, i)
			paramDecls = append(paramDecls, fmt.Sprintf("%s %s", argName, goBindingType(in.Type)))
			callArgs = append(callArgs, argName)
		}

		if m.IsConstant() {
			paramList := "ctx context.Context"
			if len(paramDecls) > 0 {
				paramList += ", " + strings.Join(paramDecls, ", ")
			}
			callSuffix := ""
			if len(callArgs) > 0 {
				callSuffix = ", " + strings.Join(callArgs, ", ")
			}
			if len(m.Outputs) == 1 && goBindingType(m.Outputs[0].Type) != "interface{}" {
				retType := goBindingType(m.Outputs[0].Type)
				fmt.Fprintf(&buf, "func (c *%s) %s(%s) (%s, error) {\n", typeName, fnName, paramList, retType)
				fmt.Fprintf(&buf, "\tvar zero %s\n", retType)
				fmt.Fprintf(&buf, "\tres, err := web3.CallConstantFunction(ctx, c.client, c.abi, c.address.Hex(), %q%s)\n", m.Sig(), callSuffix)
				fmt.Fprintf(&buf, "\tif err != nil {\n\t\treturn zero, err\n\t}\n")
				fmt.Fprintf(&buf, "\tv, _ := res[0].(%s)\n\treturn v, nil\n", retType)
				fmt.Fprintf(&buf, "}\n\n")
			} else {
				fmt.Fprintf(&buf, "func (c *%s) %s(%s) ([]interface{}, error) {\n", typeName, fnName, paramList)
				fmt.Fprintf(&buf, "\treturn web3.CallConstantFunction(ctx, c.client, c.abi, c.address.Hex(), %q%s)\n", m.Sig(), callSuffix)
				fmt.Fprintf(&buf, "}\n\n")
			}
		} else {
			paramList := "ctx context.Context, privateKeyHex string, value *big.Int, gasPrice *big.Int, gasLimit uint64"
			if len(paramDecls) > 0 {
				paramList += ", " + strings.Join(paramDecls, ", ")
			}
			callSuffix := ""
			if len(callArgs) > 0 {
				callSuffix = ", " + strings.Join(callArgs, ", ")
			}
			fmt.Fprintf(&buf, "func (c *%s) %s(%s) (*web3.Transaction, error) {\n", typeName, fnName, paramList)
			fmt.Fprintf(&buf, "\treturn web3.CallFunctionWithArgs(ctx, c.client, privateKeyHex, c.address.Hex(), value, gasPrice, gasLimit, c.abi, %q%s)\n", m.Sig(), callSuffix)
			fmt.Fprintf(&buf, "}\n\n")
		}
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("gofmt generated binding: %w", err)
	}
	return formatted, nil
}

func abiTypeUsesBigInt(t ABIType) bool {
	if (t.T == UintTy || t.T == IntTy) && (t.Size == 0 || t.Size > 64) {
		return true
	}
	return false
}

func goBindingType(t ABIType) string {
	switch t.T {
	case AddressTy:
		return "web3.Address"
	case HashTy:
		return "web3.Hash"
	case BoolTy:
		return "bool"
	case StringTy:
		return "string"
	case BytesTy:
		return "web3.HexBytes"
	case FixedBytesTy:
		if t.Size == 32 {
			return "web3.Hash"
		}
		return "web3.HexBytes"
	case UintTy:
		switch {
		case t.Size == 0 || t.Size > 64:
			return "*big.Int"
		case t.Size > 32:
			return "uint64"
		case t.Size > 16:
			return "uint32"
		case t.Size > 8:
			return "uint16"
		default:
			return "uint8"
		}
	case IntTy:
		switch {
		case t.Size == 0 || t.Size > 64:
			return "*big.Int"
		case t.Size > 32:
			return "int64"
		case t.Size > 16:
			return "int32"
		case t.Size > 8:
			return "int16"
		default:
			return "int8"
		}
	default:
		return "interface{}"
	}
}

func exportGoIdent(s string) string {
	var b strings.Builder
	upperNext := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upperNext = true
			continue
		}
		if b.Len() == 0 && unicode.IsDigit(r) {
			b.WriteByte('X')
		}
		if upperNext {
			b.WriteRune(unicode.ToUpper(r))
			upperNext = false
		} else {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "Method"
	}
	return b.String()
}

func safeParamName(name string, idx int) string {
	name = strings.TrimLeft(name, "_")
	if name == "" {
		return fmt.Sprintf("arg%d", idx)
	}
	reserved := map[string]bool{
		"type": true, "func": true, "var": true, "const": true, "package": true,
		"import": true, "return": true, "range": true, "map": true, "chan": true,
		"interface": true, "struct": true, "select": true, "default": true, "case": true,
		"go": true, "defer": true, "fallthrough": true, "if": true, "else": true,
		"switch": true, "for": true, "break": true, "continue": true, "goto": true,
		"ctx": true, "c": true, "value": true, "gasPrice": true, "gasLimit": true, "privateKeyHex": true,
		"res": true, "zero": true, "err": true, "v": true,
	}
	if reserved[name] {
		return name + "Arg"
	}
	return name
}
